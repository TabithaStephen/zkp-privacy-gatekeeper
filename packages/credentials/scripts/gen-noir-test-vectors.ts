/**
 * Generates circuits/credential-eligibility/src/test_vectors.nr.
 *
 * Signs fixed FICTIONAL credentials with the real issuer code (src/credential.ts)
 * using a throwaway key that exists only in memory. Only PUBLIC values (public
 * keys, claims, signatures) are written; the private key is discarded.
 *
 *   npx tsx scripts/gen-noir-test-vectors.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { encodeMessage, generateIssuerKeyPair, issuerPublicInfo, signLowS, type Claims } from '../src/index.ts';

const OUT = path.resolve(import.meta.dirname, '../../../circuits/credential-eligibility/src/test_vectors.nr');
const T0 = 1_767_225_600n; // 2026-01-01T00:00:00Z
const YEAR = 365n * 86_400n;

const issuer = generateIssuerKeyPair().privateKey;
const other = generateIssuerKeyPair().privateKey;

const bytes = (hex: string) =>
  '[' + (hex.match(/../g) ?? []).map((b) => `0x${b}`).join(', ') + ']';

function credential(name: string, claims: Claims): string {
  const sig = signLowS(issuer, encodeMessage(claims)).toString('hex');
  return [
    `// ${name}: income ${claims.annualIncomeInr}, valid ${claims.issuedAt}..${claims.expiresAt}`,
    `pub global ${name}_SUBJECT_ID: u64 = ${claims.subjectId};`,
    `pub global ${name}_INCOME: u64 = ${claims.annualIncomeInr};`,
    `pub global ${name}_ISSUED_AT: u64 = ${claims.issuedAt};`,
    `pub global ${name}_EXPIRES_AT: u64 = ${claims.expiresAt};`,
    `pub global ${name}_CREDENTIAL_ID: u64 = ${claims.credentialId};`,
    `pub global ${name}_SIGNATURE: [u8; 64] = ${bytes(sig)};`,
  ].join('\n');
}

const pub = issuerPublicInfo(issuer).circuit;
const otherPub = issuerPublicInfo(other).circuit;

const src = `// GENERATED by packages/credentials/scripts/gen-noir-test-vectors.ts. Do not edit.
// Public test data only: signatures from a throwaway issuer key that was never stored.
// All values are fictional.

pub global T0: u64 = ${T0}; // 2026-01-01T00:00:00Z

pub global ISSUER_X: [u8; 32] = ${bytes(pub.x)};
pub global ISSUER_Y: [u8; 32] = ${bytes(pub.y)};

// A different, untrusted issuer key.
pub global OTHER_ISSUER_X: [u8; 32] = ${bytes(otherPub.x)};
pub global OTHER_ISSUER_Y: [u8; 32] = ${bytes(otherPub.y)};

${credential('HIGH', { subjectId: 1001n, annualIncomeInr: 950_000n, issuedAt: T0, expiresAt: T0 + YEAR, credentialId: 42n })}

${credential('LOW', { subjectId: 1002n, annualIncomeInr: 650_000n, issuedAt: T0, expiresAt: T0 + YEAR, credentialId: 43n })}
`;
fs.writeFileSync(OUT, src);
console.log(`wrote ${OUT}`);
